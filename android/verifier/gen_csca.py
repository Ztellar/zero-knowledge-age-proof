"""Generates ChileCsca.kt from ZKPassport's certificate registry.

    curl -sLo certificates.json https://raw.githubusercontent.com/zkpassport/zkpassport-packages/HEAD/packages/registry-explorer/public/assets/certificates/certificates.json
    python3 -I gen_csca.py certificates.json > src/main/kotlin/cl/zkage/verifier/ChileCsca.kt

The registry only carries public keys (modulus and exponent), not whole certificates.
"""
import datetime
import hashlib
import json
import sys

path = sys.argv[1]
raw = open(path, "rb").read()
certs = [c for c in json.loads(raw)["certificates"] if c["country"] == "CHL"]
certs.sort(key=lambda c: c["validity"]["not_before"])


def day(ts):
    return datetime.datetime.fromtimestamp(ts, datetime.timezone.utc).date().isoformat()


out = [
    "// Generated by gen_csca.py. Do not edit by hand.",
    f"// Source: ZKPassport registry certificates.json, sha256 {hashlib.sha256(raw).hexdigest()}",
    "package cl.zkage.verifier",
    "",
    "import java.math.BigInteger",
    "",
    "/** Chile's country signing CA public keys (RSA), oldest first. */",
    "object ChileCsca {",
    "    val keys: List<CscaKey> = listOf(",
]
for c in certs:
    assert c["signature_algorithm"] == "RSA" and c["public_key"]["type"] == "RSA"
    v = c["validity"]
    usage = c.get("private_key_usage_period") or {}
    label = f"CHL {day(v['not_before'])[:4]} RSA{(len(c['public_key']['modulus']) - 2) * 4}"
    out += [
        "        CscaKey(",
        f'            label = "{label}",',
        f'            validFrom = "{day(v["not_before"])}",',
        f'            validUntil = "{day(v["not_after"])}",',
        f'            signsUntil = {chr(34) + day(usage["not_after"]) + chr(34) if usage else "null"},',
        f'            modulus = BigInteger("{c["public_key"]["modulus"][2:]}", 16),',
        f'            exponent = BigInteger.valueOf({c["public_key"]["exponent"]}),',
        "        ),",
    ]
out += ["    )", "}", ""]
sys.stdout.write("\n".join(out))
